import sys, os

# PyMOL colors for each kind of RAPA decision, in priority order (first match wins)
PYMOL_CATEGORIES = [
    ('rapa_degenerate', 'red', 'several states within the energy cutoff, differs between outputs'),
    ('rapa_fixed', 'slate', 'pinned with --fix'),
    ('rapa_metal', 'grey70', 'metal-coordinating HIS/CYS (HIM/CYM)'),
    ('rapa_low_confidence', 'yellow', 'assigned, but the next best state is within 1 kcal/mol (or a tie)'),
    ('rapa_flipped', 'magenta', 'side chain flipped relative to the input'),
    ('rapa_changed', 'orange', 'protonation state changed relative to the input'),
    ('rapa_unchanged', 'green', 'investigated, same as the input'),
]
LOW_CONFIDENCE_GAP = 1.0  # kcal/mol


def pymol_category(row):
    """Which PYMOL_CATEGORIES entry a summary row falls into (None for residues RAPA left alone)."""
    source = row['source']
    if source == 'degenerate_branch':
        return 'rapa_degenerate'
    if source == 'fixed':
        return 'rapa_fixed'
    if source == 'metal':
        return 'rapa_metal'
    if source == 'outside_region':
        return None  # not assigned by RAPA (outside --around), so not highlighted
    if source == 'assigned' and row['gap_to_next_best'] is not None and row['gap_to_next_best'] < LOW_CONFIDENCE_GAP:
        return 'rapa_low_confidence'
    if source in ('default', 'pair_partner_fixed') and not row['changed']:
        return None
    if row['flipped']:
        return 'rapa_flipped'
    if row['changed']:
        return 'rapa_changed'
    return 'rapa_unchanged'


def pymol_label(row):
    text = row['output_name'] + (' flip' if row['flipped'] else '')
    if row['gap_to_next_best'] is not None:
        text += f" {round(row['gap_to_next_best'], 1) + 0.0:+.1f}"
    return text


def generate_pymol_script(outputs, output_pml, ligand_names=()):
    """
    Write a PyMOL script that loads every output PDB and colors the residues RAPA investigated by how their state
    was decided (see PYMOL_CATEGORIES), labels them with state and energy gap, and stores one scene per residue.
    outputs: [(full path of output PDB, [summary rows for that output])]
    """
    def sel(row):
        return f"chain {row['chain']} and resi {row['resnum']}{row['icode']}"

    # note: PyMOL splits commands on ';' even inside comments, so the text below must not contain ';'
    with open(output_pml, 'w') as f:
        f.write("# Auto-generated by RAPA. Carbon colors show how each residue's state was decided:\n")
        for name, color, meaning in PYMOL_CATEGORIES:
            f.write(f"#   {color:<8} {name:<20} {meaning}\n")
        f.write("# Labels: state, 'flip' if flipped, and energy gap to the next best state (kcal/mol).\n")
        f.write("# Each category is also a named selection in the object panel, and each residue has a scene.\n\n")

        for i, (pdb, _) in enumerate(outputs):
            f.write(f"load {pdb}, model_{i}\n")
        f.write("bg_color white\nset label_size, 14\nset label_color, black\nset cartoon_transparency, 0.3\n"
                "hide everything, all\nshow cartoon, all\nset cartoon_color, grey80\n"
                "color grey90, elem C\n")
        if ligand_names:
            ligand_sel = ' or '.join(f"resn {name}" for name in sorted(ligand_names))
            f.write(f"select rapa_ligands, {ligand_sel}\nshow sticks, rapa_ligands\n"
                    f"color cyan, rapa_ligands and elem C\n")
        f.write("\n")

        members = {name: [] for name, _, _ in PYMOL_CATEGORIES}
        scene_residues = {}
        labels = {}  # residue key -> label texts across outputs (written once, on model_0)
        for i, (_, rows) in enumerate(outputs):
            obj = f"model_{i}"
            for row in rows:
                category = pymol_category(row)
                if category is None:
                    continue
                color = next(c for n, c, _ in PYMOL_CATEGORIES if n == category)
                key = (row['chain'], row['resnum'], row['icode'])
                style = 'lines' if category == 'rapa_unchanged' else 'sticks'
                f.write(f"show {style}, {obj} and {sel(row)} and not name N+C+O\n")
                f.write(f"color {color}, {obj} and {sel(row)} and elem C\n")
                if category != 'rapa_unchanged':
                    text = pymol_label(row)
                    labels.setdefault(key, [])
                    if text not in labels[key]:
                        labels[key].append(text)
                members[category].append(f"({obj} and {sel(row)})")
                if key not in scene_residues or category == 'rapa_degenerate':
                    scene_residues[key] = row
        # one label per residue, listing every distinct state across the outputs (e.g. "HID +0.5 | HID flip -0.5")
        for (chain, resnum, icode), texts in labels.items():
            f.write(f'label model_0 and chain {chain} and resi {resnum}{icode} and name CA, "{" | ".join(texts)}"\n')
        f.write("hide sticks, elem H\n\n")

        for name, _, _ in PYMOL_CATEGORIES:
            if members[name]:
                f.write(f"select {name}, {' or '.join(members[name])}\n")
        f.write("deselect\n\n")

        # one scene per residue that was not left unchanged, ordered by chain and number
        for key in sorted(scene_residues):
            row = scene_residues[key]
            if pymol_category(row) == 'rapa_unchanged':
                continue
            scene = f"{row['chain']}_{row['resnum']}{row['icode']}_{row['output_name']}"
            f.write(f"orient {sel(row)}\nzoom {sel(row)}, 6\n")
            f.write(f"show lines, byres (({sel(row)}) around 4) and not elem H\n")
            f.write(f"scene {scene}, store\nhide lines\n")
        f.write("zoom all\n# End of script\n")


class Logger(object):
    """
    Logger class that can simultaneously write what's printed to log file
    """

    def __init__(self,logname):
        self.terminal = sys.stdout
        self.log = open(logname, "w",buffering=1)

    def write(self, message):
        self.terminal.write(message)
        self.log.write(message)
    def flush(self):
        pass


def prettify_time(seconds):
    """
    Converts a time in seconds to a more human-readable format, handling hours, minutes, and seconds.

    Parameters:
        seconds (float): The time in seconds.

    Returns:
        str: The time in a prettified format (hours, minutes, seconds, etc.).
    """
    if seconds >= 3600:  # More than 1 hour
        hours = int(seconds // 3600)
        minutes = int((seconds % 3600) // 60)
        seconds = seconds % 60
        return f"{hours}h {minutes}m {seconds:.2f}s"
    elif seconds >= 60:  # More than 1 minute
        minutes = int(seconds // 60)
        seconds = seconds % 60
        return f"{minutes}m {seconds:.2f}s"
    elif seconds >= 1:  # More than 1 second
        return f"{seconds:.6f} seconds"
    elif seconds >= 1e-3:
        return f"{seconds * 1e3:.3f} milliseconds"
    elif seconds >= 1e-6:
        return f"{seconds * 1e6:.3f} microseconds"
    else:
        return f"{seconds * 1e9:.3f} nanoseconds"

# PDB related functions
def replace_column_range(original_line, new_value, start_col, end_col):
    """
    Replaces a specific column range (1-indexed) with a new value,
    right-aligned within that range.
    """
    # Convert 1-based PDB indexing to 0-based Python indexing
    start_idx = start_col - 1
    end_idx = end_col

    # Calculate the width of the target "slot"
    width = end_idx - start_idx

    # Format the new value:
    # '>' means right-align, 'width' sets the padding
    formatted_value = f"{str(new_value)[:width]:>{width}}"

    # Reconstruct the line
    new_line = original_line[:start_idx] + formatted_value + original_line[end_idx:]

    return new_line


def process_conect_line(line, id_map):
    """
    Processes a single CONECT line and returns a new line with updated IDs.

    Parameters:
    - line (str): The original CONECT string.
    - id_map (dict): {old_id: new_id} mapping.
    """
    # PDB CONECT columns (1-indexed):
    # Center Atom (7-11), then 4 Bonded Atoms (12-16, 17-21, 22-26, 27-31)
    column_ranges = [(7, 11), (12, 16), (17, 21), (22, 26), (27, 31)]

    new_line = list(line)  # Convert to list for easier character-level replacement

    for start, end in column_ranges:
        # Slicing the string to get the specific ID slot
        raw_val = line[start - 1:end].strip()

        if raw_val:
            old_id = int(raw_val)
            # Look up the new ID. If it's not in the map, means that ID does not need to be fixed
            new_id = id_map.get(old_id, old_id)

            # Format to right-justified string with the exact column width
            width = end - start + 1
            formatted_id = f"{new_id:>{width}}"

            # Replace the characters in the specific range
            new_line[start - 1:end] = list(formatted_id)
    return "".join(new_line)

def clean_pdb_atom_id(pdb_file):
    """
    the input PDB usually comes from MOE
    MOE will add an atom ID to TER record at the end of each chain
    and the subsequent atom ID will all continue from that TER record
    Bio PDB does not do that so the index will be different after TER record
    and CONECT record will be invalid in that case
    we should clean it by re-numbering it starting from 1 and do not assign ID to TER record
    """
    atom_id = 1
    changed_id_dict = {} # key: ori_id, value: new_id
    file_prefix = pdb_file.split('.pdb')[0]
    new_pdb_name = f'{file_prefix}_cleaned_id.pdb'
    new_pdb_f = open(new_pdb_name, 'w')
    # this is for HETATM and ANISOU will be
    with open(pdb_file, 'r') as f:
        for lc, line in enumerate(f):
            if line.startswith("ATOM") or line.startswith("HETATM"):
                # col 7-11 is atom ID
                ori_atom_id = int(line[7-1:11].strip())
                if ori_atom_id != atom_id:
                    new_line = replace_column_range(line, atom_id, 7, 11)
                    changed_id_dict[ori_atom_id] = atom_id
                    new_pdb_f.write(new_line)
                else:
                    new_pdb_f.write(line)
                atom_id += 1
            elif line.startswith("ANISOU"):
                ori_atom_id = int(line[7 - 1:11].strip())
                try:
                    new_line = replace_column_range(line, changed_id_dict[ori_atom_id], 7, 11)
                    new_pdb_f.write(new_line)
                except KeyError:
                    # if that atom_id is not in the dict that means it doesn't need to be changed
                    new_pdb_f.write(line)
            elif line.startswith("CONECT"):
                new_line = process_conect_line(line, changed_id_dict)
                new_pdb_f.write(new_line)
            else:
                new_pdb_f.write(line)
    new_pdb_f.close()
    return os.path.basename(new_pdb_name), new_pdb_name


def put_pdb_record_back(cleaned_id_pdb_file, generated_pdbs):
    """
    Bio.PDB will ignore any CONECT record, we need to append them back
    """
    # first get the CONECT record from the original PDB
    conect_lines = []
    header_lines = []
    anisou_lines = []
    anisou_atom_ids = []
    with open(cleaned_id_pdb_file, 'r') as f:
        for lc, line in enumerate(f):
            if line.startswith("CONECT"):
                conect_lines.append(line)
            elif line.startswith("HEADER"):
                header_lines.append(line)
            elif line.startswith("ANISOU"):
                anisou_lines.append(line)
                atom_id = int(line[7 - 1:11].strip())
                anisou_atom_ids.append(atom_id)
    for i in generated_pdbs:
        lines = []
        # deal with anisou record first since it needs to be following ATOM record
        with open(i, 'r') as f:
            for line in f:
                if line.startswith("ATOM") or line.startswith("HETATM"):
                    lines.append(line)
                    atom_id = int(line[7 - 1:11].strip())
                    if atom_id in anisou_atom_ids:
                        line_index = anisou_atom_ids.index(atom_id)
                        anisou_line = anisou_lines[line_index]
                        atom_name = line[13 -1:16]
                        residue_name = line[18-1:20]
                        new_line = replace_column_range(anisou_line, atom_name, 13, 16)
                        new_line = replace_column_range(new_line, residue_name, 18, 20)
                        lines.append(new_line)
                else:
                    lines.append(line)

        # remove END
        if lines[-1].startswith("END"):
            lines = lines[:-1]

        with open(i, "w") as out:
            out.writelines(header_lines)
            out.writelines(lines)
            out.writelines(conect_lines)
            out.write("END\n")